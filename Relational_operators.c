#include<stdio.h>

int main(){
	
	int num1,num2;
	printf("Enter First number (num1) : \n");
	scanf("%d",&num1);
	
	printf("Enter Second number (num2) : \n");
	scanf("%d",&num2);
	
	//Relational Operation
	printf("num1 == num2 = %d \n", num1 == num2);
	printf("num1 != num2 = %d \n", num1 != num2);
	printf("num1 > num2 = %d \n", num1 > num2);
	printf("num1 < num2 = %d \n", num1 < num2);
	printf("num1 >= num2 = %d \n", num1 >= num2);
	printf("num1 <= num2 = %d \n", num1 <= num2);
	
	
	return 0;
}
